def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def seed_worker(worker_id):
    seed = torch.initial_seed() % (2 ** 32)
    random.seed(seed)
    np.random.seed(seed)


class CheXpertImages(Dataset):
    def __init__(self, root, csv_path, training=False, seed=0, method=None):
        _, self.rows = read_rows(csv_path)
        self.root, self.training = Path(root), training
        self.method = method
        self.seed = seed
        if any(r["Frontal/Lateral"] != "Frontal" for r in self.rows):
            raise ValueError("Use frontal-only CSVs generated by prepare_chexpert_splits.py")
        # Same original Tiny uncertain-label policy for BOTH losses, deterministic per class.
        rng = random.Random(seed)
        self.uncertain_targets = {name: rng.uniform(0.7, 0.8) if name in ("Atelectasis", "Edema")
                                   else rng.uniform(0.2, 0.3) for name in CLASS_NAMES}
        self.transform = transforms.Compose([
            transforms.Resize(224, interpolation=transforms.InterpolationMode.BICUBIC, antialias=True),
            transforms.CenterCrop(224), transforms.ToTensor(),
            transforms.Normalize((0.49185243,) * 3, (0.28509309,) * 3),
        ])

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, index):
        row = self.rows[index]
        with Image.open(image_path(self.root, row["Path"])) as image:
            image = self.transform(image.convert("RGB"))
        targets, mask = [], []
        for name in CLASS_NAMES:
            value = row[name].strip()
            # Standard CheXpert convention: unmentioned=0 in BOTH training and
            # report-label evaluation. Only explicit -1 is masked for evaluation.
            observed = not value or float(value) in (0, 1)
            mask.append(observed)
            if self.training:
                target = self.uncertain_targets[name] if value and float(value) == -1 else float(value or 0)
                if self.method is not None:
                    policy = self.method["uncertain"]
                    uncertain = bool(value and float(value) == -1)
                    mask[-1] = not (uncertain and policy == "ignore")
                    if uncertain and policy in ("ones", "zeros", "ignore"):
                        target = float(policy == "ones")
                    if uncertain and policy == "soft":
                        # Stable for each image/disease across workers, epochs and resume.
                        key = "{}:{}:{}".format(self.seed, index, name)
                        target = random.Random(key).uniform(self.method["soft_low"], self.method["soft_high"])
            else:
                target = float(value or 0) if observed else 0.0
            targets.append(target)
        return image, torch.tensor(targets, dtype=torch.float32), torch.tensor(mask, dtype=torch.bool), index


def training_loss(logits, targets, loss_name="bce", smoothing=0.05):
    if loss_name not in ("bce", "label_smoothing") or not 0 <= smoothing < 1:
        raise ValueError("Invalid loss or smoothing")
    if loss_name == "label_smoothing":
        # Independent Bernoulli labels: smooth toward 0.5, never softmax across diseases.
        targets = targets * (1.0 - smoothing) + 0.5 * smoothing
    return F.binary_cross_entropy_with_logits(logits, targets)


def build_model(device):
    sys.path.insert(0, str(REPO / "compat"))
    sys.path.insert(0, str(REPO / "EVA-X/classification"))
    from timm.models import create_model
    from models import models_eva  # noqa: F401 - registers the architecture
    model = create_model(MODEL, pretrained=False, img_size=224, num_classes=5,
                         drop_path_rate=0.2, use_mean_pooling=True,
                         use_checkpoint=False, stop_grad_conv1=True)
    # Upstream detaches patch embeddings. Freeze them explicitly so DDP does not
    # wait for gradients of parameters intentionally absent from the graph.
    for parameter in model.patch_embed.parameters():
        parameter.requires_grad_(False)
    if device.type == "cpu":
        for block in model.blocks:
            block.attn.xattn = False  # CPU checks use upstream's native attention branch.
    return model.to(device)


def load_pretrained(model, path):
    if sha256(path) != TINY_MIM_SHA256:
        raise ValueError("Expected the official Tiny MIM checkpoint, not fine-tuned or incomplete weights")
    checkpoint = torch.load(path, map_location="cpu")
    state = checkpoint.get("model", checkpoint.get("module", checkpoint))
    state = {name.removeprefix("module."): value for name, value in state.items()}
    # Always initialize a fresh classifier; never start from CheXpert fine-tuned weights.
    state = {name: value for name, value in state.items() if not name.startswith("head.")}
    incompatible = model.load_state_dict(state, strict=False)
    allowed_missing = {"head.weight", "head.bias", "fc_norm.weight", "fc_norm.bias"}
    unexpected = [name for name in incompatible.unexpected_keys
                  if not name.startswith(("head.", "norm.", "mask_token", "lm_head.", "teacher."))]
    missing = [name for name in incompatible.missing_keys if name not in allowed_missing]
    if missing or unexpected:
        raise ValueError("Pretrained backbone mismatch: missing={}, unexpected={}".format(missing, unexpected))
    print("Pretrained backbone loaded; fresh 5-class head", flush=True)


def optimizer_groups(model, lr, weight_decay, layer_decay):
    groups = {}
    last = len(model.blocks) + 1
    for name, parameter in model.named_parameters():
        if not parameter.requires_grad:
            continue
        layer = int(name.split(".")[1]) + 1 if name.startswith("blocks.") else (
            0 if name in ("pos_embed", "cls_token") or name.startswith("patch_embed.") else last)
        decay = 0.0 if parameter.ndim == 1 or name in model.no_weight_decay() else weight_decay
        groups.setdefault((layer, decay), {"params": [], "lr": lr * layer_decay ** (last - layer),
                                            "weight_decay": decay})["params"].append(parameter)
    return list(groups.values())


def verify_splits(folder):
    manifest = json.loads((folder / "manifest.json").read_text())
    sets = {}
    for name in ("train", "dev", "calibration", "test"):
        path = folder / (name + ".csv")
        if sha256(path) != manifest["files"][path.name]:
            raise ValueError("Split hash mismatch: " + name)
        _, rows = read_rows(path)
        sets[name] = {patient_id(row["Path"]) for row in rows}
    for name, patients in sets.items():
        if any(patients & other for key, other in sets.items() if key != name):
            raise ValueError("Patient leakage in split manifests")
    return manifest


def make_loader(dataset, batch_size, workers, sampler=None, shuffle=False):
    return DataLoader(dataset, batch_size=batch_size, num_workers=workers,
                      pin_memory=True, sampler=sampler, shuffle=shuffle,
                      worker_init_fn=seed_worker, drop_last=False)


def autocast(device):
    return torch.autocast("cuda", dtype=torch.float16) if device.type == "cuda" else contextlib.nullcontext()


@torch.no_grad()
def evaluate(model, loader, device, method=None):
    model.eval()
    logits, targets, masks, indices = [], [], [], []
    for images, labels, mask, index in loader:
        with autocast(device):
            output = model(images.to(device, non_blocking=True))
        if method is not None:
            output = probability_logits(output, method)
        logits.append(output.float().cpu())
        targets.append(labels)
        masks.append(mask)
        indices.append(index)
    logits, targets, masks = map(torch.cat, (logits, targets, masks))
    per_element = F.binary_cross_entropy_with_logits(logits, targets, reduction="none")
    if not masks.any():
        raise ValueError("No observed binary labels in evaluation split")
    nll = float(per_element[masks].mean())
    probabilities = logits.sigmoid().numpy()
    aucs = []
    for column in range(5):
        selected = masks[:, column].numpy()
        labels = targets[:, column].numpy()[selected]
        aucs.append(float(roc_auc_score(labels, probabilities[selected, column])) if np.unique(labels).size == 2 else None)
    valid = [value for value in aucs if value is not None]
    metrics = {"auroc": float(np.mean(valid)) if valid else None, "nll": nll,
               "auroc_per_class": aucs, "observed_labels": masks.sum(0).tolist()}
    arrays = {"logits": logits.numpy(), "y_gt": targets.numpy(), "y_pred": probabilities,
              "label_mask": masks.numpy(), "indices": torch.cat(indices).numpy()}
    return metrics, arrays


def train_epoch(model, loader, optimizer, scaler, device, loss_name, smoothing, accumulation,
                method=None, clip_grad=1.0, progress=None):
    training_mode(model, method) if method else model.train()
    optimizer.zero_grad(set_to_none=True)
    total, count = 0.0, 0
    started = time.monotonic()
    for step, (images, targets, mask, _) in enumerate(loader):
        # The final partial accumulation group uses its actual number of steps.
        group_start = (step // accumulation) * accumulation
        group_samples = min(accumulation * loader.batch_size,
                            len(loader.sampler) - group_start * loader.batch_size)
        update = (step + 1) % accumulation == 0 or step + 1 == len(loader)
        synchronization = model.no_sync() if hasattr(model, "no_sync") and not update else contextlib.nullcontext()
        images, targets, mask = (x.to(device, non_blocking=True) for x in (images, targets, mask))
        if method is not None and method["loss"] == "mixup":
            images, targets, mask = mix_batch(images, targets, mask, method["mixup_alpha"])
        with synchronization:
            with autocast(device):
                logits = model(images)
                loss = objective(logits, targets, mask, method) if method else training_loss(logits, targets, loss_name, smoothing)
            if not torch.isfinite(loss):
                raise ValueError("Non-finite training loss")
            scaler.scale(loss * len(images) / group_samples).backward()
        if update:
            scaler.unscale_(optimizer)
            if clip_grad:
                torch.nn.utils.clip_grad_norm_(model.parameters(), clip_grad)
            scaler.step(optimizer)
            scaler.update()
            optimizer.zero_grad(set_to_none=True)
        total += float(loss.detach()) * len(images)
        count += len(images)
        if progress and (step % 20 == 0 or step + 1 == len(loader)):
            progress(step + 1, len(loader), total / count, time.monotonic() - started)
        if step % 50 == 0 and int(os.environ.get("RANK", "0")) == 0:
            print("step {}/{} loss={:.5f}".format(step + 1, len(loader), float(loss.detach())), flush=True)
    return total / count


def save_checkpoint(path, model, optimizer, scaler, epoch, config, best, rng_states):
    temporary = path.with_suffix(".tmp")
    torch.save({"model": model.state_dict(), "optimizer": optimizer.state_dict(), "scaler": scaler.state_dict(),
                "epoch": epoch, "config": config, "best": best, "rng_states": rng_states}, temporary)
    temporary.replace(path)


def current_rng(device):
    return {"python": random.getstate(), "numpy": np.random.get_state(), "torch": torch.get_rng_state(),
            "cuda": torch.cuda.get_rng_state(device) if device.type == "cuda" else None}


def restore_rng(state, device):
    random.setstate(state["python"])
    np.random.set_state(state["numpy"])
    torch.set_rng_state(state["torch"])
    if device.type == "cuda":
        torch.cuda.set_rng_state(state["cuda"], device)


def run(args):
    method = method_config(json.loads(args.experiment_config.read_text())) if getattr(args, "experiment_config", None) else None
    clip_grad = getattr(args, "clip_grad", 1.0)
    patience = getattr(args, "patience", 0)
    min_epochs = getattr(args, "min_epochs", 1)
    min_delta = getattr(args, "min_delta", 0.0)
    rank, world = int(os.environ.get("RANK", "0")), int(os.environ.get("WORLD_SIZE", "1"))
    local_rank = int(os.environ.get("LOCAL_RANK", "0"))
    device = torch.device("cpu" if args.cpu else "cuda", None if args.cpu else local_rank)
    if device.type == "cuda":
        torch.cuda.set_device(device)
    if world > 1:
        if args.stage != "train":
            raise ValueError("Use one process for check/evaluate")
        dist.init_process_group("gloo" if args.cpu else "nccl")
    try:
        seed_everything(args.seed + rank)
        torch.backends.cudnn.benchmark = False
        torch.backends.cudnn.deterministic = True
        manifest = verify_splits(args.splits_dir)
        config = {"model": MODEL, "loss": args.loss, "smoothing": args.smoothing if args.loss == "label_smoothing" else 0.0,
                  "seed": args.seed, "epochs": args.epochs, "batch_size_per_gpu": args.batch_size,
                  "world_size": world, "accumulation": args.accumulation, "lr": args.lr,
                  "weight_decay": args.weight_decay, "layer_decay": args.layer_decay,
                  "split_manifest_sha256": sha256(args.splits_dir / "manifest.json"),
                  "class_order": list(CLASS_NAMES), "selection": "dev AUROC (tie: observed-label NLL)",
                  "uncertain_policy": "original Tiny per-class soft targets, missing=0, shared seed",
                  "torch_version": torch.__version__, "trainer_sha256": sha256(Path(__file__)),
                  "architecture_sha256": sha256(REPO / "EVA-X/classification/models/models_eva.py"),
                  "pretrained_sha256": sha256(args.pretrained) if args.stage != "evaluate" else None}
        if method is not None:
            config.update(method=method, clip_grad=clip_grad,
                          loss=method["loss"], smoothing=method["smoothing"] if method["loss"] == "label_smoothing" else 0.,
                          uncertain_policy=method["uncertain"] + "; missing=0",
                          early_stopping=dict(patience=patience, min_epochs=min_epochs, min_delta=min_delta),
                          methods_sha256=sha256(REPO / "scripts/calibration_methods.py"))
        model = build_model(device)
        if args.stage in ("train", "check"):
            load_pretrained(model, args.pretrained)
        if args.stage == "evaluate":
            checkpoint = torch.load(args.checkpoint, map_location="cpu")
            saved_method = checkpoint["config"].get("method")
            if method is not None and method != saved_method:
                raise ValueError("Evaluation method differs from checkpoint")
            method = saved_method
        if method is not None:
            configure_scope(model, method)
            config["trainable_parameters"] = sum(p.numel() for p in model.parameters() if p.requires_grad)
        if args.stage == "check":
            dataset = CheXpertImages(args.data_root, args.splits_dir / "train.csv", True, args.seed, method)
            images, targets, _, _ = next(iter(make_loader(dataset, min(2, args.batch_size), 0)))
            training_mode(model, method) if method else model.train()
            with autocast(device):
                if method:
                    images, targets, mask, _ = next(iter(make_loader(dataset, min(2, args.batch_size), 0)))
                    images, targets, mask = (x.to(device) for x in (images, targets, mask))
                    if method["loss"] == "mixup":
                        images, targets, mask = mix_batch(images, targets, mask, method["mixup_alpha"])
                    loss = objective(model(images), targets, mask, method)
                else:
                    loss = training_loss(model(images.to(device)), targets.to(device), args.loss, args.smoothing)
            loss.backward()
            gradients = [p.grad for p in model.parameters() if p.requires_grad]
            if not torch.isfinite(loss) or any(g is None or not torch.isfinite(g).all() for g in gradients):
                raise ValueError("Preflight gradient check failed")
            print("CHECK OK: checkpoint, real images, {} loss/backward; no optimizer step".format(method["loss"] if method else args.loss), flush=True)
            if getattr(args, "check_receipt", None):
                atomic_json(args.check_receipt, dict(config=config, checked_at=now(), loss=float(loss.detach()),
                                                    trainable_parameters=sum(p.numel() for p in model.parameters() if p.requires_grad)))
            return
        if args.stage == "evaluate":
            if checkpoint["config"]["split_manifest_sha256"] != config["split_manifest_sha256"]:
                raise ValueError("Evaluation must use the training run's original splits")
            model.load_state_dict(checkpoint["model"], strict=True)
            dataset = CheXpertImages(args.data_root, args.splits_dir / (args.eval_split + ".csv"))
            metrics, arrays = evaluate(model, make_loader(dataset, args.batch_size, args.workers), device, method)
            args.output_dir.mkdir(parents=True, exist_ok=False)
            for name, array in arrays.items():
                np.save(args.output_dir / (name + ".npy"), array)
            # Keep exact CSV order, image IDs and patient IDs for future patient bootstrap.
            (args.output_dir / "samples.json").write_text(json.dumps([
                {"path": row["Path"], "patient_id": patient_id(row["Path"])} for row in dataset.rows], indent=2))
            (args.output_dir / "evaluation.json").write_text(json.dumps({"metrics": metrics, "split": args.eval_split,
                "checkpoint_sha256": sha256(args.checkpoint), "checkpoint_epoch": checkpoint["epoch"] + 1,
                "training_config": checkpoint["config"],
                "logits_semantics": "Bernoulli log odds (SPA inverse link applied when relevant)"}, indent=2))
            # For report-derived dev/calibration labels, masked arrays are not input to the strict 0/1 metric CLI.
            if not arrays["label_mask"].all():
                print("This split has unobserved labels: use label_mask.npy; do not run the unmasked calibration CLI.")
            print(json.dumps(metrics, indent=2), flush=True)
            return
        train_data = CheXpertImages(args.data_root, args.splits_dir / "train.csv", True, args.seed, method)
        dev_data = CheXpertImages(args.data_root, args.splits_dir / "dev.csv") if rank == 0 else None
        sampler = DistributedSampler(train_data, num_replicas=world, rank=rank, shuffle=True, seed=args.seed)
        loader = make_loader(train_data, args.batch_size, args.workers, sampler=sampler)
        dev_loader = make_loader(dev_data, args.batch_size, args.workers) if rank == 0 else None
        if world > 1:
            model = torch.nn.parallel.DistributedDataParallel(model, device_ids=None if args.cpu else [local_rank])
        bare_model = model.module if world > 1 else model
        optimizer = torch.optim.AdamW(optimizer_groups(bare_model, args.lr, args.weight_decay, args.layer_decay))
        scaler = torch.cuda.amp.GradScaler(enabled=device.type == "cuda")
        start, best = 0, (-math.inf, -math.inf)
        if method is not None:
            best = (*best, -math.inf, -1)
        if args.resume:
            saved = torch.load(args.resume, map_location="cpu")
            if saved["config"] != config:
                raise ValueError("Resume configuration differs; keep loss, splits, seed and training settings identical")
            bare_model.load_state_dict(saved["model"])
            optimizer.load_state_dict(saved["optimizer"])
            scaler.load_state_dict(saved["scaler"])
            start, best = saved["epoch"] + 1, tuple(saved["best"])
            restore_rng(saved["rng_states"][rank], device)
        if rank == 0:
            if args.resume and args.output_dir.resolve() != args.resume.resolve().parent:
                raise ValueError("Resume into the original run directory")
            if not args.resume and args.output_dir.exists() and any(
                    path.name != "run.log" for path in args.output_dir.iterdir()):
                raise ValueError("Run directory is not empty; choose a new output directory")
            args.output_dir.mkdir(parents=True, exist_ok=True)
            if args.resume:
                history = args.output_dir / "history.jsonl"
                records = []
                for line in history.read_text().splitlines() if history.exists() else []:
                    try:
                        record = json.loads(line)
                    except json.JSONDecodeError:
                        break  # Preserve only committed epoch records after interrupted writes.
                    if record["epoch"] <= start:
                        records.append(json.dumps(record))
                history.write_text("\n".join(records) + ("\n" if records else ""))
            (args.output_dir / "config.json").write_text(json.dumps(config, indent=2) + "\n")
            print(json.dumps(config, indent=2), flush=True)
            print("True epochs: {}; training images: {}; effective batch: {}".format(
                args.epochs, len(train_data), args.batch_size * world * args.accumulation), flush=True)
        if world > 1:
            dist.barrier()
        if method is not None and patience and start >= min_epochs and start - 1 - best[3] >= patience:
            if rank == 0:
                print("Previously early-stopped checkpoint is complete", flush=True)
            return
        for epoch in range(start, args.epochs):
            stop = False
            epoch_started = time.monotonic()
            sampler.set_epoch(epoch)
            def progress(step, total, loss_value, elapsed):
                atomic_json(args.output_dir / "progress.json", dict(updated_at=now(), phase="training",
                    epoch=epoch + 1, epochs=args.epochs, step=step, steps=total, train_loss=loss_value,
                    epoch_elapsed_seconds=elapsed, epoch_eta_seconds=elapsed / step * (total - step),
                    gpu_peak_memory_mb=torch.cuda.max_memory_allocated(device) / 2**20 if device.type == "cuda" else 0))
            loss = train_epoch(model, loader, optimizer, scaler, device, args.loss, args.smoothing, args.accumulation,
                               method, clip_grad, progress if rank == 0 else None)
            if rank == 0:
                atomic_json(args.output_dir / "progress.json", dict(updated_at=now(), phase="dev_evaluation",
                    epoch=epoch + 1, epochs=args.epochs))
            metrics = evaluate(bare_model, dev_loader, device, method)[0] if rank == 0 else None
            states = [None] * world
            if world > 1:
                dist.all_gather_object(states, current_rng(device))
            else:
                states[0] = current_rng(device)
            if rank == 0:
                if metrics["auroc"] is None:
                    raise ValueError("Dev split cannot select AUROC: no disease has both classes")
                score = (metrics["auroc"], -metrics["nll"])
                improved = score > best
                early_auc, early_epoch = best[2:] if method is not None else (None, None)
                if method is not None and metrics["auroc"] > early_auc + min_delta:
                    early_auc, early_epoch = metrics["auroc"], epoch
                if improved:
                    best = score
                if method is not None:
                    best = (*best[:2], early_auc, early_epoch)
                    stop = bool(patience and epoch + 1 >= min_epochs and epoch - early_epoch >= patience)
                if improved:
                    save_checkpoint(args.output_dir / "best.pth", bare_model, optimizer, scaler, epoch, config, best, states)
                save_checkpoint(args.output_dir / "last.pth", bare_model, optimizer, scaler, epoch, config, best, states)
                record = {"epoch": epoch + 1, "train_loss_rank0": loss, "dev": metrics,
                          "epoch_seconds": time.monotonic() - epoch_started, "early_stopped": stop}
                with (args.output_dir / "history.jsonl").open("a") as handle:
                    handle.write(json.dumps(record) + "\n")
                print(json.dumps(record), flush=True)
                atomic_json(args.output_dir / "progress.json", dict(record, updated_at=now(),
                    phase="complete" if stop or epoch + 1 == args.epochs else "epoch_complete", epochs=args.epochs))
            if world > 1:
                flag = torch.tensor(int(stop), device=device)
                dist.broadcast(flag, src=0)
                stop = bool(flag.item())
                dist.barrier()
            if stop:
                if rank == 0:
                    print("EARLY STOP: dev AUROC plateau; best checkpoint preserved", flush=True)
                break
        if rank == 0:
            print("TRAIN COMPLETE. Official test and calibration splits were not evaluated. Best: " + str(args.output_dir / "best.pth"))
    finally:
        if dist.is_initialized():
            dist.destroy_process_group()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=("check", "train", "evaluate"))
    parser.add_argument("--loss", choices=("bce", "label_smoothing"), default="bce")
    parser.add_argument("--smoothing", type=float, default=0.05)
    parser.add_argument("--data-root", type=Path, required=True)
    parser.add_argument("--splits-dir", type=Path, required=True)
    parser.add_argument("--pretrained", type=Path)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--checkpoint", type=Path)
    parser.add_argument("--eval-split", choices=("dev", "calibration", "test"), default="test")
    parser.add_argument("--resume", type=Path)
    parser.add_argument("--epochs", type=int, default=5)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--workers", type=int, default=8)
    parser.add_argument("--accumulation", type=int, default=1)
    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--weight-decay", type=float, default=0.05)
    parser.add_argument("--layer-decay", type=float, default=0.55)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--cpu", action="store_true", help="Small CPU verification only; not intended for full training")
    parser.add_argument("--experiment-config", type=Path, help="Study method JSON; absent preserves the legacy two-loss experiment")
    parser.add_argument("--check-receipt", type=Path)
    parser.add_argument("--clip-grad", type=float, default=1.0, help="0 disables gradient clipping")
    parser.add_argument("--patience", type=int, default=0, help="0 disables early stopping; study methods only")
    parser.add_argument("--min-epochs", type=int, default=1)
    parser.add_argument("--min-delta", type=float, default=0.0001)
    args = parser.parse_args()
    if min(args.epochs, args.batch_size, args.accumulation) < 1 or args.workers < 0 or args.lr <= 0:
        parser.error("Invalid training dimensions or learning rate")
    if not 0 <= args.smoothing < 1 or not 0 < args.layer_decay <= 1 or args.weight_decay < 0:
        parser.error("Invalid smoothing, layer decay or weight decay")
    if not math.isfinite(args.clip_grad) or args.clip_grad < 0:
        parser.error("clip-grad must be finite and nonnegative")
    if args.patience < 0 or args.min_epochs < 1 or args.min_epochs > args.epochs or not math.isfinite(args.min_delta) or args.min_delta < 0:
        parser.error("Invalid early stopping settings")
    if args.stage in ("check", "train") and (not args.pretrained or not args.pretrained.is_file() or args.pretrained.stat().st_size == 0):
        parser.error("Specify a nonempty Tiny MIM --pretrained file")
    if args.stage != "check" and args.output_dir is None:
        parser.error("--output-dir is required")
    if args.stage == "evaluate" and not args.checkpoint:
        parser.error("--checkpoint is required")
    run(args)


if __name__ == "__main__":
    main()
